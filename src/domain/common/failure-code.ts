/**
 * FailureCode taxonomy — stable, machine-readable codes used by providers
 * to decide whether to retry, correct the payload, or give up.
 */
export enum FailureCode {
  INSUFFICIENT_BALANCE = 'INSUFFICIENT_BALANCE',
  INVALID_REFERENCE = 'INVALID_REFERENCE',
  REFERENCE_NOT_FOUND = 'REFERENCE_NOT_FOUND',
  REFERENCE_EXPIRED = 'REFERENCE_EXPIRED',
  ALREADY_PROCESSED = 'ALREADY_PROCESSED',
  CONFLICTING_PAYLOAD = 'CONFLICTING_PAYLOAD',
  NEGATIVE_BALANCE_WOULD_RESULT = 'NEGATIVE_BALANCE_WOULD_RESULT',
  REFERENCE_ALREADY_REVERSED = 'REFERENCE_ALREADY_REVERSED',
  INVALID_KIND_FOR_REFERENCE = 'INVALID_KIND_FOR_REFERENCE',
  MOEDA_MISMATCH = 'MOEDA_MISMATCH',
  INFRASTRUCTURE_ERROR = 'INFRASTRUCTURE_ERROR',
}

export const BUSINESS_FAILURE_CODES = new Set<FailureCode>([
  FailureCode.INSUFFICIENT_BALANCE,
  FailureCode.INVALID_REFERENCE,
  FailureCode.REFERENCE_NOT_FOUND,
  FailureCode.REFERENCE_EXPIRED,
  FailureCode.ALREADY_PROCESSED,
  FailureCode.CONFLICTING_PAYLOAD,
  FailureCode.NEGATIVE_BALANCE_WOULD_RESULT,
  FailureCode.REFERENCE_ALREADY_REVERSED,
  FailureCode.INVALID_KIND_FOR_REFERENCE,
  FailureCode.MOEDA_MISMATCH,
]);

export function isBusinessFailure(code: FailureCode): boolean {
  return BUSINESS_FAILURE_CODES.has(code);
}
